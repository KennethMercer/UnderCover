<#
.SYNOPSIS
  Builds installer\dist\UnderCover-Setup-<version>.exe from the current code (local only; never publish it).

  1. Writes installer\addons.isi (the optional add-ons page) from the add-ons registry, so the installer and the app
     list the same add-ons with the same licence summaries (undercover/core/addons.py).
  2. Runs Inno Setup's ISCC on UnderCover.iss.

  powershell -ExecutionPolicy Bypass -File installer\build.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$py = Join-Path $root '.venv\Scripts\python.exe'

# 0. What ships from disk is whole (phase 25): Agent Smoke's binaries aren't in git (scripts/make_demo_voice.py makes
#    them), so they're checked against their manifest; the sample song, its classified full version and the greetings
#    must be there. A build that would ship a broken First assignment stops here.
Push-Location $root
try {
    $why = & $py -c "from undercover.app import tutorial; print(tutorial.demo_files() or '')"
    if ($LASTEXITCODE -ne 0) { throw "couldn't check the demo voice" }
    if ($why) { throw "The demo voice can't ship: $why" }
} finally { Pop-Location }
$assets = Join-Path $root 'undercover\assets'
foreach ($f in @('sample\sample.json', 'sample\hold-on.mp3', 'sample\classified\hold-on (full).mp3',
                 'demo-voice\greetings\greetings.json', 'demo-voice\agent-smoke\tts\ref.wav', 'reader-prints.json')) {
    if (-not (Test-Path (Join-Path $assets $f))) { throw "Missing from the build: undercover\assets\$f" }
}
$greet = Get-Content (Join-Path $assets 'demo-voice\greetings\greetings.json') -Raw | ConvertFrom-Json
foreach ($g in @($greet.greetings) + @($greet.followon)) {
    if (-not (Test-Path (Join-Path $assets "demo-voice\greetings\$($g.file)"))) { throw "Missing greeting clip: $($g.file)" }
}
$mb = [math]::Round(((Get-ChildItem (Join-Path $root 'undercover') -Recurse -File | Where-Object { $_.FullName -notmatch '__pycache__' } | Measure-Object Length -Sum).Sum) / 1MB, 1)
Write-Host "Shipped app files: $mb MB (Agent Smoke checked against its manifest; sample song, classified file, greetings present)"
$json = & $py -m undercover.addons list --json
if ($LASTEXITCODE -ne 0) { throw "python -m undercover.addons list --json failed" }
$all = $json | Out-String | ConvertFrom-Json   # Windows PowerShell hands the whole array on as one item
$addons = @($all | ForEach-Object { $_ } | Where-Object { $_.optional -and $_.installable })
function Pas([string]$s) { "'" + $s.Replace("'", "''") + "'" }
$ids = @(); $caps = @(); $urls = @()
for ($i = 0; $i -lt $addons.Count; $i++) {
    $a = $addons[$i]
    $gb = '{0:0.0}' -f ($a.size_mb / 1000)
    $ids  += "    $i`: Result := $(Pas $a.id);"
    $caps += "    $i`: Result := $(Pas "$($a.name), about $gb GB ($($a.licence)): $($a.adds) $($a.licence_summary)");"
    $urls += "    $i`: Result := $(Pas $a.licence_url);"
}
function Fn([string]$name, [string[]]$cases) {
    if (-not $cases.Count) { return "function $name(I: Integer): String;`r`nbegin`r`n  Result := '';`r`nend;`r`n" }
    "function $name(I: Integer): String;`r`nbegin`r`n  Result := '';`r`n  case I of`r`n" + ($cases -join "`r`n") + "`r`n  end;`r`nend;`r`n"
}
$isi = "// Generated by installer\build.ps1 from undercover/core/addons.py; don't edit by hand.`r`n" +
       "const`r`n  ADDON_COUNT = $($addons.Count);`r`n`r`n" + (Fn 'AddonId' $ids) + "`r`n" + (Fn 'AddonCaption' $caps) + "`r`n" + (Fn 'AddonUrl' $urls)
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'addons.isi'), $isi, (New-Object Text.UTF8Encoding $true))
Write-Host "addons.isi: $($addons.Count) optional add-on(s): $(($addons | ForEach-Object { $_.id }) -join ', ')"

$ver = (Get-Content (Join-Path $root 'undercover\VERSION') -Raw).Trim()
if ($ver -notmatch '^\d+\.\d+\.\d+$') { throw "undercover\VERSION should hold a version like 1.0.0, not '$ver'" }
Write-Host "Version $ver (undercover\VERSION)"
$iscc = @("$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe", "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw "Inno Setup 6 (ISCC.exe) isn't installed." }
& $iscc (Join-Path $PSScriptRoot 'UnderCover.iss')
if ($LASTEXITCODE -ne 0) { throw "ISCC failed ($LASTEXITCODE)" }
Get-ChildItem (Join-Path $PSScriptRoot 'dist') | Format-Table Name, Length, LastWriteTime -AutoSize
