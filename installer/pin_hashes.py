"""Regenerate the installer's requirement files from the dev venv, with a SHA-256 for every package (phase 4b).

    .venv\\Scripts\\python.exe installer\\pin_hashes.py

Writes requirements/common.txt (everything except PyTorch and the cadence set), requirements/cadence.txt (the cadence
engine's packages, installed --no-deps like on the dev PC; the list is constraints.txt's cadence section) and the
--hash lines of requirements/torch-{cpu,cuda126,cuda128}.txt. Hashes come from PyPI's JSON API and the PyTorch index
(their published SHA-256 per file; nothing is downloaded). Only files a Windows x64 / CPython 3.12 install can use are
listed. uv checks every hash it is given and refuses a file that doesn't match.

Pins move only after tools/smoke.py --full passed on the new versions (ARCHITECTURE.md "Resilience and self-healing").
"""
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REQ = HERE / "requirements"
SKIP = {"torch", "torchaudio", "torchvision", "rocm", "rocm-sdk-core", "rocm-sdk-devel", "rocm-sdk-libraries-custom"}
TORCH = {"cpu": "cpu", "cuda126": "cu126", "cuda128": "cu128"}


def norm(n: str) -> str:
    return re.sub(r"[-_.]+", "-", n).lower()


def usable(fn: str) -> bool:
    """A wheel a Windows x64 CPython 3.12 install can use (cp312, abi3 from an older CPython, or pure Python)."""
    if not fn.endswith(".whl"):
        return False
    py, abi, plat = fn[:-4].split("-")[-3:]
    if not any(t in ("win_amd64", "any") for t in plat.split(".")):
        return False
    for p in py.split("."):
        for a in abi.split("."):
            if a == "none" and (p.startswith("py3") or p in ("py2.py3", "cp312")):
                return True
            if a == "abi3" and p.startswith("cp3") and p[2:].isdigit() and int(p[3:] or 0) <= 12:
                return True
            if a == "cp312" and p == "cp312":
                return True
    return False


SOURCE_OK = {"antlr4-python3-runtime", "openai-whisper", "encodec", "transformers-stream-generator"}   # no wheels at all on PyPI; pure Python, builds without a compiler


def pypi_hashes(name: str, version: str) -> list[str]:
    """The SHA-256 of every wheel that fits; a source archive only for the few pure-Python packages that ship no
    wheel (anything else would need a compiler on a friend's PC, so it's refused here instead)."""
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as r:
        files = [(u["filename"], u["digests"]["sha256"]) for u in json.load(r)["urls"]]
    wheels = [h for f, h in files if usable(f)]
    if wheels:
        return wheels
    if norm(name) in SOURCE_OK:
        return [h for f, h in files if f.endswith((".tar.gz", ".zip"))]
    raise SystemExit(f"{name}=={version}: no wheel for Windows / Python 3.12 on PyPI (a source build needs a compiler)")


def torch_hashes(tag: str, name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://download.pytorch.org/whl/{tag}/{name}/", timeout=60) as r:
        html = r.read().decode()
    want = f"{name}-{version}".replace("+", "%2B")
    out = [h for f, h in re.findall(r'href="[^"]*?/([^/"#]+\.whl)#sha256=([0-9a-f]{64})"', html)
           if f.startswith(want + "-") and f.endswith("cp312-cp312-win_amd64.whl")]
    if not out:
        raise SystemExit(f"{name}=={version}: not on download.pytorch.org/whl/{tag}")
    return out


def line(name: str, version: str, hashes: list[str]) -> str:
    return f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes)


def cadence_names() -> list[str]:
    text = (ROOT / "constraints.txt").read_text(encoding="utf-8")
    block = text.split("# Cadence engine", 1)[1]
    return [norm(m.group(1)) for m in re.finditer(r"(?m)^([A-Za-z0-9_.\-]+)==", block)]


def main():
    frz = subprocess.run([str(ROOT / ".venv" / "Scripts" / "python.exe"), "-m", "pip", "freeze"], capture_output=True,
                         text=True, check=True).stdout
    pins = {}
    for l in frz.splitlines():
        if "==" in l and not l.startswith("#"):
            n, v = l.split("==", 1)
            pins[norm(n)] = (n, v.strip())
    cad = cadence_names()
    missing = [c for c in cad if c not in pins]
    if missing:
        raise SystemExit(f"constraints.txt lists cadence packages the venv doesn't have: {missing}")
    head = ("# Every package except PyTorch and the cadence set, pinned to the dev venv and SHA-256 checked.\n"
            "# Generated by installer/pin_hashes.py; don't edit by hand (re-run it after an approved, smoke-tested change).\n"
            "# Installed AFTER torch-<backend>.txt, constrained to the torch that was just installed.\n")
    common = [line(n, v, pypi_hashes(n, v)) for k, (n, v) in sorted(pins.items()) if k not in SKIP and k not in cad]
    (REQ / "common.txt").write_text(head + "\n".join(common) + "\n", encoding="utf-8")
    chead = ("# The cadence engine (Chatterbox 0.1.7 + Whisper, phase 4): installed --no-deps, like on the dev PC (their\n"
             "# metadata pins torch 2.6 / numpy < 2, which would replace the GPU's torch). SHA-256 checked.\n"
             "# Generated by installer/pin_hashes.py from constraints.txt's cadence section; don't edit by hand.\n")
    cadl = [line(*pins[c], pypi_hashes(*pins[c])) for c in cad]
    (REQ / "cadence.txt").write_text(chead + "\n".join(cadl) + "\n", encoding="utf-8")
    torch_v = {"torch": "2.9.1", "torchaudio": "2.9.1", "torchvision": "0.24.1"}
    for backend, tag in TORCH.items():
        f = REQ / f"torch-{backend}.txt"
        comments = [l for l in f.read_text(encoding="utf-8").splitlines() if l.startswith("#")]
        body = [line(n, f"{v}+{tag}", torch_hashes(tag, n, f"{v}+{tag}")) for n, v in torch_v.items()]
        f.write_text("\n".join(comments) + "\n" + "\n".join(body) + "\n", encoding="utf-8")
    # the optional add-ons' packages (core/addons.py): requirements/addon-<id>.txt, used by addons.install when present
    sys.path.insert(0, str(ROOT))
    from undercover.core import addons
    from undercover.core import cadence  # noqa: F401  (registers F5-TTS, XTTS-v2)
    for a in addons.ADDONS.values():
        if a.included or not a.wired or not a.packages:
            continue
        lines = [line(*p.split("==", 1), pypi_hashes(*p.split("==", 1))) for p in a.packages]
        (REQ / f"addon-{a.id}.txt").write_text(
            f"# {a.name} ({a.licence}): its Python packages, installed --no-deps with these hashes by core/addons.py.\n"
            "# Generated by installer/pin_hashes.py from the registry; don't edit by hand.\n" + "\n".join(lines) + "\n",
            encoding="utf-8")
    print(f"common.txt: {len(common)} packages · cadence.txt: {len(cadl)} · torch: {', '.join(TORCH)}")


if __name__ == "__main__":
    sys.exit(main())
